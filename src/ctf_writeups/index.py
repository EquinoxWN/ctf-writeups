"""Render the technique index and write files atomically."""

from __future__ import annotations

import os
import tempfile
from collections import Counter
from pathlib import Path

from ctf_writeups.techniques import CATEGORIES, Technique
from ctf_writeups.validate import WRITEUPS_DIR, WriteUp

HEADER = "<!-- Generated by `ctfw index` from the write-ups and techniques.toml. Do not edit by hand. -->"


def _cell(text: str) -> str:
    """Escape a value for a Markdown table cell."""
    return text.replace("\\", "\\\\").replace("|", "\\|").replace("\n", " ")


def render_index(writeups: list[WriteUp], vocab: dict[str, Technique]) -> str:
    """The index page: counts per category, then every write-up under each technique."""
    by_tech: dict[str, list[WriteUp]] = {t: [] for t in vocab}
    for wu in writeups:
        for t in wu.techniques:
            by_tech.setdefault(t, []).append(wu)
    cats = Counter(wu.category for wu in writeups)
    lines = [HEADER, "", "# Write-ups by technique", ""]
    lines += [f"{len(writeups)} write-ups, {sum(1 for t in by_tech if by_tech[t])} techniques covered.", ""]
    lines += ["| Category | Write-ups |", "|---|---|"]
    lines += [f"| {c} | {cats[c]} |" for c in CATEGORIES]
    lines.append("")
    covered = sorted((t for t in by_tech if by_tech[t]), key=lambda t: (vocab[t].name.lower(), t))
    for tid in covered:
        tech = vocab[tid]
        cwe = f" ({tech.cwe})" if tech.cwe else ""
        lines += [f"## {_cell(tech.name)}{cwe}", "", f"`{tid}` · {tech.category}", ""]
        lines += ["| Write-up | Category | Difficulty | Platform | Solved |", "|---|---|---|---|---|"]
        for wu in sorted(by_tech[tid], key=lambda w: (w.category, w.slug)):
            link = Path(wu.path).relative_to(WRITEUPS_DIR).as_posix()
            lines.append(
                f"| [{_cell(wu.title)}]({link}) | {wu.category} | {wu.difficulty} | {_cell(wu.platform)} | {wu.solved.isoformat()} |"
            )
        lines.append("")
    missing = sorted((t for t in vocab if not by_tech[t]), key=lambda t: (vocab[t].name.lower(), t))
    if missing:
        lines += ["## Not covered yet", ""]
        lines += [f"- {_cell(vocab[t].name)} (`{t}`, {vocab[t].category})" for t in missing]
        lines.append("")
    return "\n".join(lines)


def write_atomic(path: Path, text: str) -> None:
    """Write text through a sibling temp file and rename, so readers never see half a file."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp, path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise
